#!/usr/bin/env python3
"""run_eval.py — score the SAM3 teacher on the held-out split, through SAM3's own hydra harness.

Unlike yolo/coco_eval.py, this is orchestration, not scoring: the actual COCOeval run happens
inside SAM3/sam3/train/train.py's Trainer (hydra + DDP + pycocotools), which is Meta's own
reference implementation and the thing that was verified this session to produce bit-identical
numbers across two conda environments. Reimplementing that harness here, rather than driving it,
would risk exactly what pipeline/EVALUATION.md warns against for the paper repros: "a reproduction
whose number is computed by different code is not a comparison." See ../README.md for the full
pipeline trace and the numbers this was checked against.

What this script does, that running train.py by hand does not:
  1. Copies configs/pcatcher_eval.yaml (the version-controlled source of truth) into
     SAM3/sam3/train/configs/roboflow_v100/_pcatcher_eval_generated.yaml. Hydra's
     `initialize_config_module("sam3.train")` can only compose configs that live inside that
     package's own configs/ directory, so the canonical copy has to live in pipeline/ and get
     dropped into place at run time rather than being pointed at directly.
  2. Sets PYTHONPATH to the SAM3 submodule root, so this works even under the `sam3` conda env,
     whose editable `sam3` install is shadowed by an unrelated repo (see
     project_conda_env_ald.md) — though `ald` is the recommended env and needs no such fix.
  3. Reads the run's val_stats.json + coco_predictions_bbox.json when it's done and prints a
     report in the same five-metric shape yolo/coco_eval.py uses, plus writes a coco_metrics.json
     into the run's own directory.

Usage
-----
    PY=/home/zklab/miniconda3/envs/ald/bin/python
    $PY run_eval.py                    # default config, ald python, 1 GPU
    $PY run_eval.py --python /path/to/python --gpus 1
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parent.parent.parent
SAM3_ROOT = REPO_ROOT / "SAM3"
GENERATED_CONFIG_NAME = "_pcatcher_eval_generated.yaml"
GENERATED_CONFIG_REL = f"configs/roboflow_v100/{GENERATED_CONFIG_NAME}"

DEFAULT_PYTHON = "/home/zklab/miniconda3/envs/ald/bin/python"

# Mirrors yolo/coco_eval.py's STAT_INDEX / REPORTED, and SAM3's own COCO_METRICS naming
# (sam3/eval/coco_eval_offline.py) — same six numbers, different label vocabulary to translate.
METRIC_KEYS = {
    "mAP50": "AP_50",
    "mAP50-95": "AP",
    "APs": "AP_small",
    "APm": "AP_medium",
    "APl": "AP_large",
    # AR@100, IoU 0.50:0.05:0.95, all areas -- the companion to mAP50-95 and the same
    # quantity yolo/coco_eval.py reads from COCOeval.stats[8]. SAM3's offline evaluator
    # already computes it; this only stops it being discarded.
    "AR": "AR_maxDets@100",
}
REPORTED = ("mAP50", "mAP50-95", "APs", "APm", "APl", "AR")


# Keys whose value is a filesystem path stored relative to REPO_ROOT. train.py runs with SAM3/
# as its cwd, so these are made absolute when the config is staged. Values already absolute, and
# hydra interpolations (${...}), are left alone.
PATH_KEYS = (
    "roboflow_vl_100_root",
    "experiment_log_dir",
    "bpe_path",
    "img_folder",
    "ann_file",
    "checkpoint_path",
    "gt_path",
)
_PATH_LINE = re.compile(
    rf"^(\s*(?:{'|'.join(PATH_KEYS)}):[ \t]+)(?![/$])(\S+)[ \t]*$", re.MULTILINE
)


def absolutize(value: str) -> str:
    """Make a REPO_ROOT-relative config path absolute. Absolute values pass through unchanged."""
    path = Path(value)
    return value if path.is_absolute() else str(REPO_ROOT / path)


def stage_config(config_path: Path) -> Path:
    """Copy the canonical config into SAM3's config search path. Returns the path train.py needs.

    Rewrites PATH_KEYS values from REPO_ROOT-relative to absolute as it copies. This is done
    textually rather than through yaml.safe_load/dump, which would drop the ~50 explanatory
    comments the config carries.

    Hydra's `# @package _global_` directive must be the file's FIRST line to be recognized — a
    provenance header prepended above it silently breaks config composition (every top-level key
    ends up "not in struct", since hydra no longer merges it as _global_). So the header goes
    after that line, not before.
    """
    dest_dir = SAM3_ROOT / "sam3/train/configs/roboflow_v100"
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / GENERATED_CONFIG_NAME

    lines = config_path.read_text().splitlines(keepends=True)
    if not lines or not lines[0].startswith("# @package"):
        raise SystemExit(f"{config_path} must start with a '# @package' directive on line 1")
    header = (
        "# GENERATED by pipeline/evaluation/sam3/run_eval.py — do not edit here.\n"
        f"# Source of truth: pipeline/evaluation/sam3/configs/{config_path.name}\n\n"
    )
    body = _PATH_LINE.sub(lambda m: m.group(1) + absolutize(m.group(2)), "".join(lines[1:]))
    dest.write_text(lines[0] + header + body)
    return dest


def run_train(python: str, gpus: int) -> None:
    cmd = [
        python, "sam3/train/train.py",
        "-c", GENERATED_CONFIG_REL,
        "--use-cluster", "0",
        "--num-gpus", str(gpus),
    ]
    print(f"+ {' '.join(cmd)}\n  (cwd={SAM3_ROOT}, PYTHONPATH={SAM3_ROOT})", flush=True)
    result = subprocess.run(
        cmd, cwd=SAM3_ROOT, env={**os.environ, "PYTHONPATH": str(SAM3_ROOT)},
    )
    if result.returncode != 0:
        raise SystemExit(f"train.py exited {result.returncode} — see output above.")


def find_outputs(cfg: dict) -> tuple[Path, Path]:
    """Resolve val_stats.json and coco_predictions_bbox.json from the config's own paths."""
    exp_dir = Path(absolutize(cfg["paths"]["experiment_log_dir"]))
    supercategory = cfg["all_roboflow_supercategories"][0]
    val_stats = exp_dir / "logs" / supercategory / "val_stats.json"
    preds = exp_dir / "dumps" / "roboflow" / supercategory / "coco_predictions_bbox.json"
    if not val_stats.is_file():
        raise SystemExit(f"train.py finished but no val_stats.json at {val_stats}")
    return val_stats, preds


def report(val_stats_path: Path, preds_path: Path, config_path: Path) -> dict:
    raw = json.loads(val_stats_path.read_text())
    # "Meters_train/val_roboflow100/detection/coco_eval_bbox_AP" -> strip the trailing "_AP" to
    # get the shared prefix every other metric key hangs off (..._AP_50, ..._AP_small, etc.).
    ap_key = next(k for k in raw if k.startswith("Meters_") and k.endswith("_AP"))
    prefix = ap_key[: -len("_AP")]

    metrics = {name: raw[f"{prefix}_{sam3_key}"] for name, sam3_key in METRIC_KEYS.items()}
    ap75 = raw.get(f"{prefix}_AP_75")

    n_detections = n_images = max_per_image = None
    if preds_path.is_file():
        preds = json.loads(preds_path.read_text())
        n_detections = len(preds)
        per_image: dict = {}
        for p in preds:
            per_image[p["image_id"]] = per_image.get(p["image_id"], 0) + 1
        n_images = len(per_image)
        max_per_image = max(per_image.values()) if per_image else 0

    payload = {
        "metrics": metrics,
        "mAP75": ap75,
        "n_detections": n_detections,
        "n_images": n_images,
        "max_detections_per_image": max_per_image,
        "provenance": {
            "config": str(config_path),
            "val_stats_json": str(val_stats_path),
            "predictions_json": str(preds_path) if preds_path.is_file() else None,
            "scorer": "pycocotools.cocoeval.COCOeval (via SAM3's CocoEvaluatorOfflineWithPredFileEvaluators)",
        },
    }

    bar = "=" * 62
    print(f"\n{bar}\n  SAM3 teacher — held-out split\n{bar}")
    for name in REPORTED:
        print(f"  {name:<10} {metrics[name]:.4f}")
    if ap75 is not None:
        print(f"  mAP75      {ap75:.4f}")
    if n_detections is not None:
        density = f"{n_detections / n_images:.1f}/image" if n_images else "n/a"
        print(f"  {n_detections:,} detections over {n_images:,} images ({density}, max {max_per_image}/image)")
    print(bar)

    out_path = val_stats_path.parent.parent.parent / "coco_metrics.json"
    out_path.write_text(json.dumps(payload, indent=2) + "\n")
    print(f"Wrote {out_path}")
    return payload


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", default=str(HERE / "configs" / "pcatcher_eval.yaml"))
    parser.add_argument("--python", default=DEFAULT_PYTHON, help="interpreter that runs train.py")
    parser.add_argument("--gpus", type=int, default=1)
    parser.add_argument("--skip-run", action="store_true",
                         help="skip launching train.py; just report an already-finished run's val_stats.json")
    args = parser.parse_args()

    config_path = Path(args.config).resolve()
    if not config_path.is_file():
        raise SystemExit(f"config not found: {config_path}")
    cfg = yaml.safe_load(config_path.read_text())

    if not args.skip_run:
        stage_config(config_path)
        run_train(args.python, args.gpus)

    val_stats_path, preds_path = find_outputs(cfg)
    report(val_stats_path, preds_path, config_path)


if __name__ == "__main__":
    main()
